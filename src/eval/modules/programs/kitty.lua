-- Ported from Home Manager's modules/programs/kitty.nix (MIT); see tests/hm/cases.toml for the commit.
local t = archix.types
local f = archix.formats

local function config_value(v)
  if type(v) == "boolean" then return f.yes_no(v) end
  return f.nix_string(v)
end

local function lines_of(map, prefix, separator)
  local out = {}
  for key, value in pairs(map) do out[#out + 1] = prefix .. key .. separator .. value .. "\n" end
  return table.concat(out)
end

local function shell_mode(mode)
  local modes = { "no-rc" }
  for m in mode:gmatch("%S+") do
    if m ~= "no-rc" then modes[#modes + 1] = m end
  end
  return table.concat(modes, " ")
end

return {
  options = {
    programs = {
      kitty = {
        enable = archix.option { type = t.bool, default = false, description = "Install and configure kitty." },
        package = archix.option { type = t.nullable(t.str), default = "kitty" },
        font = archix.option {
          type = t.nullable(t.submodule {
            name = archix.option { type = t.str },
            size = archix.option { type = t.any, default = archix.null, description = "Points; 8 renders as 8, 8.5 as 8.500000, like Home Manager." },
          }),
          default = archix.null,
        },
        settings = archix.option { type = t.attrs_of(t.any), default = {}, description = "kitty.conf settings; booleans become yes/no." },
        keybindings = archix.option { type = t.attrs_of(t.str), default = {} },
        mouse_bindings = archix.option { type = t.attrs_of(t.str), default = {} },
        action_aliases = archix.option { type = t.attrs_of(t.str), default = {} },
        environment = archix.option { type = t.attrs_of(t.str), default = {} },
        extra_config = archix.option { type = t.lines, default = "" },
        quick_access_terminal_config = archix.option { type = t.attrs_of(t.any), default = {} },
        diff_config = {
          settings = archix.option { type = t.attrs_of(t.any), default = {} },
          keybindings = archix.option { type = t.attrs_of(t.str), default = {} },
          extra_config = archix.option { type = t.lines, default = "" },
        },
        shell_integration = {
          mode = archix.option {
            type = t.nullable(t.str),
            default = "no-rc",
            description = "kitty's shell_integration; no-rc is always implied, null turns integration off.",
          },
          enable_zsh_integration = archix.option { type = t.bool, default = true },
        },
      },
    },
  },
  config = function(cfg)
    local kitty = cfg.programs.kitty
    if not kitty.enable then return {} end
    local fragments = {}
    if kitty.font ~= nil then
      local size = kitty.font.size ~= nil and ("font_size " .. f.nix_string(kitty.font.size)) or ""
      fragments[#fragments + 1] = "font_family " .. kitty.font.name .. "\n" .. size .. "\n"
    end
    local mode = kitty.shell_integration.mode
    if mode ~= nil then
      fragments[#fragments + 1] = "# Shell integration is sourced and configured manually\nshell_integration " .. shell_mode(mode) .. "\n"
    end
    if next(kitty.settings) then fragments[#fragments + 1] = f.key_value(kitty.settings, { value = config_value }) end
    if next(kitty.action_aliases) then fragments[#fragments + 1] = lines_of(kitty.action_aliases, "action_alias ", " ") end
    if next(kitty.keybindings) then fragments[#fragments + 1] = lines_of(kitty.keybindings, "map ", " ") end
    if next(kitty.mouse_bindings) then fragments[#fragments + 1] = lines_of(kitty.mouse_bindings, "mouse_map ", " ") end
    if next(kitty.environment) then fragments[#fragments + 1] = lines_of(kitty.environment, "env ", "=") end
    if kitty.extra_config ~= "" then fragments[#fragments + 1] = kitty.extra_config end

    local files = {
      [".config/kitty/kitty.conf"] = {
        text = "# Generated by archix.\n# See https://sw.kovidgoyal.net/kitty/conf.html\n" .. table.concat(fragments, "\n") .. "\n",
      },
    }
    if next(kitty.quick_access_terminal_config) then
      files[".config/kitty/quick-access-terminal.conf"] = {
        text = "# Generated by archix.\n# See https://sw.kovidgoyal.net/kitty/kittens/quick-access-terminal/\n"
          .. f.key_value(kitty.quick_access_terminal_config, { value = config_value }) .. "\n",
      }
    end
    local diff = {}
    if next(kitty.diff_config.settings) then diff[#diff + 1] = f.key_value(kitty.diff_config.settings, { value = config_value }) end
    if next(kitty.diff_config.keybindings) then diff[#diff + 1] = lines_of(kitty.diff_config.keybindings, "map ", " ") end
    if kitty.diff_config.extra_config ~= "" then diff[#diff + 1] = kitty.diff_config.extra_config end
    if #diff > 0 then
      files[".config/kitty/diff.conf"] = {
        text = "# Generated by archix\n# See https://sw.kovidgoyal.net/kitty/kittens/diff/\n" .. table.concat(diff, "\n") .. "\n",
      }
    end

    local result = { home = { files = files } }
    if kitty.package ~= nil then result.packages = { kitty.package } end
    if mode ~= nil and kitty.shell_integration.enable_zsh_integration and cfg.programs.zsh.enable then
      result.programs = {
        zsh = {
          init_content = 'if test -n "$KITTY_INSTALLATION_DIR"; then\n  export KITTY_SHELL_INTEGRATION="'
            .. shell_mode(mode)
            .. '"\n  autoload -Uz -- "$KITTY_INSTALLATION_DIR"/shell-integration/zsh/kitty-integration\n  kitty-integration\n  unfunction kitty-integration\nfi\n',
        },
      }
    end
    return result
  end,
}
